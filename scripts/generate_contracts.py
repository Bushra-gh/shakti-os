"""Generate portable TypeScript wire models from Pydantic, without a running API.

Run with the API Python environment. --check verifies generated output without
writing; --mobile PATH also checks/updates the independently built Expo copy.
No application/DB imports, private dotenv or network connections are needed.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services/api/src"))

from pydantic import BaseModel, TypeAdapter

from shaktios_api.api_models import Health, Integrations, Me, PublicOverview, VoiceConfig
from shaktios_api.gemma_models import GemmaConfig, IncidentBrief, IncidentBriefRequest, PhotoTriageRequest, PhotoTriageResponse
from shaktios_api.incident_models import ActionDelivery, Incident, IncidentAction, IncidentStatusUpdate
from shaktios_api.models import CameraDetection, Event
from shaktios_api.priority_models import PriorityAssessment, PriorityRequest
from shaktios_api.report_contracts import Category, ReportStatus, Urgency
from shaktios_api.report_models import ReportEvent
from shaktios_api.timeline_models import TimelineEntry
from shaktios_api.venue_models import Venue
from shaktios_api.voice_provider import VoiceDraft

# Response fields are always serialized (including default null/empty values).
# Request fields retain optionality for fields with Pydantic defaults.
OUTPUT_MODELS = (
    Event, Incident, ReportEvent, Venue, TimelineEntry, ActionDelivery, Health,
    Me, Integrations, PublicOverview, VoiceConfig, VoiceDraft, PriorityAssessment,
    GemmaConfig, PhotoTriageResponse, IncidentBrief,
)
INPUT_MODELS = (CameraDetection, IncidentStatusUpdate, IncidentAction, PriorityRequest, PhotoTriageRequest, IncidentBriefRequest)


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts_type(value) for value in schema["anyOf"]))
    kind = schema.get("type")
    if kind in {"integer", "number"}:
        return "number"
    if kind in {"string", "boolean", "null"}:
        return kind
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        if "properties" in schema:
            required = schema.get("required", [])
            fields = "; ".join(
                f"{json.dumps(key)}{'' if key in required else '?'}: {ts_type(value)}"
                for key, value in schema["properties"].items()
            )
            return f"{{ {fields} }}"
        additional = schema.get("additionalProperties", True)
        if additional is False:
            return "Record<string, never>"
        return f"Record<string, {ts_type(additional) if isinstance(additional, dict) else 'unknown'}>"
    if not schema or set(schema) <= {"title", "description"}:
        return "unknown"
    raise ValueError(f"Unsupported contract schema: {schema}")


def render_contracts() -> str:
    definitions: dict[str, dict] = {}
    for models, mode in ((OUTPUT_MODELS, "serialization"), (INPUT_MODELS, "validation")):
        for model in models:
            schema = model.model_json_schema(mode=mode, by_alias=True)
            nested = schema.pop("$defs", {})
            for name, value in {**nested, model.__name__: schema}.items():
                if mode == "serialization" and value.get("type") == "object":
                    value["required"] = list(value.get("properties", {}))
                if name in definitions and definitions[name] != value:
                    raise ValueError(f"Conflicting validation/serialization schemas for {name}")
                definitions[name] = value

    for name, literal in (("IncidentCategoryId", Category), ("Urgency", Urgency), ("ReportStatus", ReportStatus)):
        definitions[name] = TypeAdapter(literal).json_schema()

    lines = [
        "// Generated by shakti-os/scripts/generate_contracts.py from Pydantic models.",
        "// Do not edit: regenerate and run --check after API contract changes.",
        "",
    ]
    constant_names = {
        "IncidentStatus": "INCIDENT_STATUSES", "IncidentSeverity": "INCIDENT_SEVERITIES",
        "ReportStatus": "REPORT_STATUSES", "IncidentCategoryId": "CATEGORY_IDS", "Urgency": "URGENCIES",
    }
    for name, schema in sorted(definitions.items()):
        if name in constant_names:
            values = json.dumps(schema["enum"], ensure_ascii=False)
            lines.append(f"export const {constant_names[name]} = {values} as const;")
        if schema.get("type") == "object" and "properties" in schema:
            lines.append(f"export interface {name} {{")
            required = schema.get("required", [])
            for field, value in schema["properties"].items():
                optional = "" if field in required else "?"
                lines.append(f"  {field}{optional}: {ts_type(value)};")
            lines.append("}")
        else:
            lines.append(f"export type {name} = {ts_type(schema)};")
        lines.append("")
    lines.extend([
        "// Client writes omit identity and incident links, both assigned by the server.",
        'export type EventInput = Omit<Event, "id" | "timestamp" | "reporter_id" | "incident_id"> &',
        '  Partial<Pick<Event, "id" | "timestamp">>;',
        "export type CameraDetectionInput = CameraDetection;",
        "export type CitizenReport = ReportEvent;",
        "export type VoiceFields = DraftFields;",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--mobile", type=Path, help="Sibling Expo repository to update/check")
    args = parser.parse_args()
    targets = [ROOT / "packages/types/src/generated.ts"]
    if args.mobile:
        target = args.mobile.resolve() / "src/types/contracts.ts"
        if not target.parent.is_dir():
            parser.error("--mobile must point to an Expo checkout with src/types")
        targets.append(target)
    content = render_contracts()
    stale = []
    for target in targets:
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(str(target))
        else:
            target.write_text(content, encoding="utf-8", newline="\n")
            print(f"Generated {target}")
    if stale:
        print("Stale API contracts; run the generator for: " + ", ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print("API contracts match Pydantic models")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
